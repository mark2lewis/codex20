export function BrandLink({
  href,
  label,
  children,
  className,
  size = "md",
  external = true,
}: {
  href: string;
  label: string;
  children: ReactNode;
  className?: string;
  size?: "sm" | "md" | "lg";
  external?: boolean;
}) {
  const dim =
    size === "lg" ? "size-14" : size === "sm" ? "size-9" : "size-11";
  return (
    <a
      href={href}
      aria-label={label}
      {...(external
        ? { target: "_blank", rel: "noopener noreferrer" }
        : {})}
      className={cn(
        "brand-badge inline-flex shrink-0 items-center justify-center",
        dim,
        className,
      )}
    >
      {children}
    </a>
  );
}
